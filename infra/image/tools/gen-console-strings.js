// Generates the console string tables (ocinye-firstboot, ocinye-oie) from the
// D013 Design package's reference/d013/strings.js, unchanged: the Design text
// is the source of truth. Usage:
//   node infra/image/tools/gen-console-strings.js <path to strings.js>
const fs = require('fs');
const path = require('path');
global.window = {};
eval(fs.readFileSync(process.argv[2], 'utf8'));
const T = window.D13_T;
const keys = Object.keys(T).filter(k => k.startsWith('c13.') || k.startsWith('st.')).sort();
let out = '// Generated by infra/image/tools/gen-console-strings.js from the D013 Design\n' +
  '// package (reference/d013/strings.js), unchanged. Regenerate; do not edit.\n' +
  'pub const STRINGS: &[(&str, [&str; 3])] = &[\n';
for (const k of keys) out += `    (${JSON.stringify(k)}, [${T[k].map(s => JSON.stringify(s)).join(', ')}]),\n`;
out += '];\n';
const root = path.resolve(__dirname, '../../..');
for (const svc of ['firstboot', 'oie']) fs.writeFileSync(path.join(root, 'services', svc, 'src', 'strings.rs'), out);
console.log(keys.length + ' keys');
